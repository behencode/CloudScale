"""Description and category providers.

`local` providers are development aids and say so in every response.
`bedrock` and `sagemaker` call AWS and surface failures unchanged.
"""

import json

from botocore.exceptions import BotoCoreError, ClientError

from app.aws_session import aws_config, aws_session, provider_error
from app.constants import CATEGORIES
from app.errors import ConfigurationError, ProviderError

_KEYWORDS = (
    ("lost-and-found", ("lost", "found", "missing", "wallet", "keys", "key", "id card", "backpack")),
    ("textbooks", ("textbook", "book", "edition", "isbn", "coursebook")),
    ("housing", ("room", "apartment", "rent", "sublet", "roommate", "lease", "flat")),
    ("events", ("event", "meetup", "workshop", "ticket", "concert", "seminar")),
    ("community", ("volunteer", "club", "giveaway", "free", "help", "tutoring")),
)


class LocalDescriptionService:
    provider = "local-template"

    def generate(self, *, title: str, category: str, details: str) -> dict:
        extra = details.strip() or "No extra details were provided."
        description = (
            f"{title.strip()} is a {category} listing on CampusConnect. {extra} "
            "Meet in a public campus place and confirm the details before you exchange anything."
        )
        return {
            "description": description,
            "provider": self.provider,
            "model_id": None,
            "notice": "Generated by the local development template. Amazon Bedrock was not called.",
        }


class BedrockDescriptionService:
    provider = "amazon-bedrock"

    def __init__(self, client, model_id: str, max_tokens: int = 256):
        if not model_id:
            raise ConfigurationError("BEDROCK_MODEL_ID is required when DESCRIPTION_PROVIDER=bedrock.")
        self.client = client
        self.model_id = model_id
        self.max_tokens = max_tokens

    def generate(self, *, title: str, category: str, details: str) -> dict:
        prompt = (
            "Write one short listing description for a university community board. "
            "Use plain sentences. Do not invent a price, phone number, or exact time. "
            f"Title: {title}\nCategory: {category}\nDetails: {details or 'none'}"
        )
        try:
            response = self.client.converse(
                modelId=self.model_id,
                system=[{"text": "You write concise, factual campus listing descriptions."}],
                messages=[{"role": "user", "content": [{"text": prompt}]}],
                inferenceConfig={"maxTokens": self.max_tokens, "temperature": 0.4},
            )
        except (ClientError, BotoCoreError) as exc:
            raise provider_error("Amazon Bedrock", exc) from exc
        blocks = response.get("output", {}).get("message", {}).get("content", [])
        text = " ".join(block.get("text", "") for block in blocks if isinstance(block, dict)).strip()
        if not text:
            raise ProviderError("Amazon Bedrock returned an empty description.")
        return {
            "description": text[:4000],
            "provider": self.provider,
            "model_id": self.model_id,
            "notice": "Generated by Amazon Bedrock. This request used your AWS account and can incur charges.",
        }


class LocalCategoryService:
    provider = "local-keyword-classifier"

    def predict(self, *, title: str, details: str) -> dict:
        text = f"{title} {details}".lower()
        scores = []
        for category, words in _KEYWORDS:
            hits = sum(1 for word in words if word in text)
            scores.append((hits, category))
        hits, category = max(scores, key=lambda item: item[0])
        if hits == 0:
            category = "community"
            confidence = 0.35
        else:
            confidence = min(0.95, 0.45 + hits * 0.15)
        return {
            "category": category,
            "confidence": round(confidence, 2),
            "provider": self.provider,
            "endpoint_name": None,
            "notice": "Predicted by the local keyword classifier. Amazon SageMaker was not called.",
        }


class SageMakerCategoryService:
    provider = "amazon-sagemaker"

    def __init__(self, client, endpoint_name: str):
        if not endpoint_name:
            raise ConfigurationError(
                "SAGEMAKER_ENDPOINT_NAME is required when CATEGORY_PROVIDER=sagemaker."
            )
        self.client = client
        self.endpoint_name = endpoint_name

    def predict(self, *, title: str, details: str) -> dict:
        payload = json.dumps({"title": title, "details": details}).encode("utf-8")
        try:
            response = self.client.invoke_endpoint(
                EndpointName=self.endpoint_name,
                ContentType="application/json",
                Accept="application/json",
                Body=payload,
            )
            raw_body = response["Body"]
            try:
                raw = raw_body.read()
            finally:
                raw_body.close()
        except (ClientError, BotoCoreError) as exc:
            raise provider_error("Amazon SageMaker", exc) from exc
        try:
            parsed = json.loads(raw.decode("utf-8"))
        except (UnicodeError, json.JSONDecodeError) as exc:
            raise ProviderError("Amazon SageMaker returned a body that is not JSON.") from exc
        category = _category_from_payload(parsed)
        if category not in CATEGORIES:
            raise ProviderError(
                "Amazon SageMaker returned a category CampusConnect does not use: "
                f"{category!r}. Expected one of {', '.join(CATEGORIES)}."
            )
        confidence = parsed.get("confidence", parsed.get("score", 0)) if isinstance(parsed, dict) else 0
        try:
            confidence = float(confidence)
        except (TypeError, ValueError):
            confidence = 0.0
        return {
            "category": category,
            "confidence": confidence,
            "provider": self.provider,
            "endpoint_name": self.endpoint_name,
            "notice": "Predicted by Amazon SageMaker. This request used your AWS account and can incur charges.",
        }


def _category_from_payload(parsed) -> str:
    if isinstance(parsed, dict):
        for key in ("category", "predicted_label", "label"):
            value = parsed.get(key)
            if isinstance(value, str):
                return value.strip().lower()
    raise ProviderError(
        "Amazon SageMaker JSON must include category, predicted_label, or label. "
        f"Received keys: {sorted(parsed.keys()) if isinstance(parsed, dict) else type(parsed).__name__}."
    )


def build_description_service(settings):
    if settings.description_provider == "local":
        return LocalDescriptionService()
    if settings.description_provider == "bedrock":
        client = aws_session(settings).client("bedrock-runtime", config=aws_config())
        return BedrockDescriptionService(client, settings.bedrock_model_id, settings.bedrock_max_tokens)
    raise ConfigurationError(f"Unknown description provider: {settings.description_provider}")


def build_category_service(settings):
    if settings.category_provider == "local":
        return LocalCategoryService()
    if settings.category_provider == "sagemaker":
        client = aws_session(settings).client("sagemaker-runtime", config=aws_config())
        return SageMakerCategoryService(client, settings.sagemaker_endpoint_name)
    raise ConfigurationError(f"Unknown category provider: {settings.category_provider}")
